#!/usr/bin/env python3
"""tools/amalgamate.py — fold include/silk into one distributable header.

    python3 tools/amalgamate.py            # writes dist/silk.hpp

Local #include "..." directives are replaced **in place** (textually, like
the C preprocessor) so that macros defined before an #include line also apply
to the inlined content — that ordering matters for the stb implementation
macros in text/font.hpp. System includes (<GLFW/glfw3.h>, <OpenGL/gl3.h>,
STL) are kept as-is. Each source header is emitted exactly once.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INCLUDE = ROOT / "include"
OUT = ROOT / "dist" / "silk.hpp"

ORDER = [
    "silk/core/math.hpp",
    "silk/core/color.hpp",
    "silk/core/input.hpp",
    "silk/core/time.hpp",
    "silk/core/utf8.hpp",
    "silk/layout/layout.hpp",
    "silk/render/draw_list.hpp",
    "silk/render/sink.hpp",
    "silk/style/theme.hpp",
    "silk/style/anim.hpp",
    # NOTE: the stb detail headers are NOT listed here — text/font.hpp defines
    # STB*_STATIC + *_IMPLEMENTATION and includes them itself; the inliner
    # keeps that macro ordering intact.
    "silk/text/font.hpp",
    "silk/text/system_fonts.hpp",
    "silk/widgets/env.hpp",
    "silk/widgets/widget.hpp",
    "silk/widgets/containers.hpp",
    "silk/widgets/controls.hpp",
    "silk/widgets/inputs.hpp",
    "silk/widgets/text.hpp",
    "silk/widgets/views.hpp",
    "silk/widgets/all.hpp",
    "silk/context.hpp",
    "silk/backends/software/software.hpp",
    "silk/backends/opengl/opengl.hpp",
    "silk/backends/glfw/glfw_window.hpp",
    "silk/silk.hpp",
]

INCLUDE_RE = re.compile(r'[ \t]*#include[ \t]+"([^"]+)"')


def resolve(includer: Path, name: str) -> Path | None:
    candidates = [
        includer.parent / name,          # file-relative ("detail/stb_truetype.h")
        INCLUDE / name,                  # include-root relative ("silk/core/...")
        INCLUDE / "silk" / name,         # silk-root relative ("core/...")
    ]
    for c in candidates:
        if c.is_file():
            return c
    return None


def process(path: Path, visited: set) -> str:
    rel = path.relative_to(INCLUDE).as_posix()
    if rel in visited:
        return f"// (already included above: {rel})\n"
    visited.add(rel)

    text = path.read_text()
    text = re.sub(r"[ \t]*#pragma once[ \t]*\n", "", text)

    # Substitute includes LINE BY LINE: stb's doc comments contain example
    # "#include" lines that must not be inlined. A real directive starts its
    # own line (stb_truetype.h's self-references inside #if 0 example blocks
    # resolve to an "already included" comment — harmless).
    include_line = re.compile(r'^[ \t]*#include[ \t]+"([^"]+)"')
    out_lines = []
    for line in text.splitlines(keepends=True):
        m = include_line.match(line)
        if m:
            target = resolve(path, m.group(1))
            if target is None:
                sys.exit(f"error: cannot resolve {m.group(1)!r} from {rel}")
            out_lines.append(process(target, visited))
        else:
            out_lines.append(line)
    body = "".join(out_lines)
    banner = "// " + "=" * 76 + f"\n// {rel}\n// " + "=" * 76 + "\n"
    return f"{banner}{body}\n"


def main() -> None:
    visited: set = set()
    parts = [process(INCLUDE / rel, visited) for rel in ORDER]

    license_lines = "".join(f"// {line}\n" for line in (ROOT / "LICENSE").read_text().strip().splitlines())
    header = f"""// dist/silk.hpp — single-header distribution of the silk UI library.
// Generated by tools/amalgamate.py — do not edit by hand.
//
// Everything is included: core, widgets, software rasterizer, system OpenGL
// backend, and the GLFW wrapper (optional at compile time). Fonts are the
// vendored public-domain stb_truetype/stb_rect_pack, compiled with internal
// linkage, so any number of TUs may include this header.
//
// Usage:
//   #include "silk.hpp"
//
{license_lines}\
// ---------------------------------------------------------------------------

#ifndef SILK_AMALGAMATED_HPP
#define SILK_AMALGAMATED_HPP

"""
    footer = "\n#endif // SILK_AMALGAMATED_HPP\n"

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(header + "\n".join(parts) + footer)
    lines = OUT.read_text().count("\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({lines} lines, {OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
