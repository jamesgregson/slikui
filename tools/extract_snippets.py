#!/usr/bin/env python3
"""tools/extract_snippets.py — lift # doc: marked regions into docs includes.

The docs quote real demo code, never copies. Shipped examples mark the
regions that belong on doc pages:

    # doc: <slug>
    class Meter(slikui.Widget):
        ...
    # doc: end

This script copies each marked region into
docs/includes/examples/<slug>.md as a fenced python block, headed by a
source comment that names the file and slug:

    <!-- source: python/slikui/examples/paint.py#meter — edit the source,
         then rerun tools/extract_snippets.py; do not edit this file -->

    ```python
    ...
    ```

doc_check.py verifies every `--8<-- "includes/examples/*.md"` target on a
docs page names a file whose header source still has live markers, so
renames/moves fail the docs build instead of rotting quietly.

Usage:
    python tools/extract_snippets.py              # regenerate all
    python tools/extract_snippets.py --list       # show what would be written
    python tools/extract_snippets.py --check      # exit 1 if outputs are stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXAMPLES = ROOT / "python" / "slikui" / "examples"
OUT = ROOT / "docs" / "includes" / "examples"

BEGIN = re.compile(r"^#\s*doc:\s*([\w-]+)\s*$")
END = re.compile(r"^#\s*doc:\s*end\s*$")


def regions_of(path: Path) -> dict[str, str]:
    """slug → region source (markers excluded, trailing blank lines trimmed)."""
    regions: dict[str, str] = {}
    slug: str | None = None
    body: list[str] = []
    for line in path.read_text().splitlines():
        if slug is None:
            m = BEGIN.match(line)
            if m:
                slug, body = m.group(1), []
            continue
        if END.match(line):
            while body and not body[-1].strip():
                body.pop()
            indent = min((len(l) - len(l.lstrip()) for l in body if l.strip()),
                         default=0)
            regions[slug] = "\n".join(l[indent:] if l.strip() else ""
                                      for l in body)
            slug = None
            continue
        body.append(line)
    if slug is not None:
        raise SystemExit(f"extract_snippets: unclosed # doc: {slug!r} in {path}")
    return regions


def include_text(source: str, slug: str, code: str) -> str:
    return (f"<!-- source: {source}#{slug} — edit the source, then rerun\n"
            "     tools/extract_snippets.py; do not edit this file -->\n\n"
            "```python\n" + code + "\n```\n")


def collect() -> dict[str, tuple[str, str]]:
    """slug → (source rel path, region source), across all example modules."""
    found: dict[str, tuple[str, str]] = {}
    for path in sorted(EXAMPLES.glob("*.py")):
        if path.name.startswith("_"):
            continue
        rel = path.relative_to(ROOT).as_posix()
        for slug, code in regions_of(path).items():
            if slug in found:
                raise SystemExit(f"extract_snippets: duplicate slug {slug!r} "
                                 f"in {rel} and {found[slug][0]}")
            found[slug] = (rel, code)
    return found


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--list", action="store_true", help="print found slugs")
    p.add_argument("--check", action="store_true",
                   help="exit 1 if written outputs are stale")
    args = p.parse_args()

    found = collect()
    if args.list:
        for slug, (source, _) in found.items():
            print(f"{slug:<16} <- {source}")
        return 0

    stale: list[str] = []
    for slug, (source, code) in found.items():
        target = OUT / f"{slug}.md"
        want = include_text(source, slug, code)
        have = target.read_text() if target.exists() else None
        if have != want:
            stale.append(f"{target.relative_to(ROOT)} (from {source}#{slug})")
            if not args.check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(want)

    if args.check:
        if stale:
            print("extract_snippets: stale outputs — rerun without --check:")
            for s in stale:
                print("  -", s)
            return 1
        print(f"extract_snippets: {len(found)} include(s) up to date")
        return 0

    print(f"extract_snippets: wrote {len(found)} include(s) to "
          f"{OUT.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
