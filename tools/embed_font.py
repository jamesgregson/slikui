#!/usr/bin/env python3
"""tools/embed_font.py — embed the bundled TTF as a C++ byte array.

    python3 tools/embed_font.py     # writes include/slikui/text/default_font.hpp

Input is third_party/fonts/DejaVuSans-subset.ttf (see the README there for
provenance and how to regenerate the subset). The output header is
self-contained (<cstddef>/<cstdint> only) so it can also ship next to the
amalgamated dist/slikui.hpp unchanged.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "third_party" / "fonts" / "DejaVuSans-subset.ttf"
OUT = ROOT / "include" / "slikui" / "text" / "default_font.hpp"
PER_LINE = 24


def main() -> None:
    data = FONT.read_bytes()
    rows = []
    for i in range(0, len(data), PER_LINE):
        rows.append("    " + ",".join(str(b) for b in data[i:i + PER_LINE]) + ",")
    body = "\n".join(rows)
    OUT.write_text(f"""\
// slikui/text/default_font.hpp — bundled fallback font (DejaVu Sans subset).
// Generated by tools/embed_font.py from third_party/fonts/DejaVuSans-subset.ttf
// — do not edit by hand.
//
// Opt-in: nothing else in slikui includes this header, so apps that ship
// their own fonts don't pay its ~{len(data) // 1024} KB. Coverage: ASCII, Latin-1, General
// Punctuation, euro, trademark, arrows, check mark.
//
//   #include <slikui/text/default_font.hpp>
//   ctx.load_font_memory(slikui::text::default_font_data(),
//                        slikui::text::default_font_size());
//
// Font licence (Bitstream Vera / Arev; DejaVu changes are public domain):
// third_party/fonts/LICENSE-DejaVu.txt — redistribute it with the font.
// Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved. Bitstream Vera
// is a trademark of Bitstream, Inc.
// Copyright (c) 2006 by Tavmjong Bah. All Rights Reserved.
#pragma once

#include <cstddef>
#include <cstdint>

namespace slikui::text {{

namespace detail {{
inline constexpr std::uint8_t kDefaultFontTTF[{len(data)}] = {{
{body}
}};
}} // namespace detail

inline const std::uint8_t* default_font_data() noexcept {{ return detail::kDefaultFontTTF; }}
inline constexpr std::size_t default_font_size() noexcept {{ return sizeof(detail::kDefaultFontTTF); }}

}} // namespace slikui::text
""")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(data)} bytes embedded, "
          f"{OUT.stat().st_size // 1024} KB source)")


if __name__ == "__main__":
    main()
