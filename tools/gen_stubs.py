#!/usr/bin/env python3
"""tools/gen_stubs.py — regenerate python/slikui/_slikui.pyi.

The compiled module's type stub is generated by nanobind's stubgen (vendored
in third_party/nanobind) from the *installed* extension, plus the patterns in
tools/stub_patterns.txt, and committed. python/tests/test_stubs.py fails when
the committed stub drifts from the built module.

    python tools/gen_stubs.py            # rewrite the committed stub
    python tools/gen_stubs.py --check    # exit 1 if it would change
"""

from __future__ import annotations

import argparse
import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
STUBGEN = ROOT / "third_party" / "nanobind" / "src" / "stubgen.py"
PATTERNS = ROOT / "tools" / "stub_patterns.txt"
STUB = ROOT / "python" / "slikui" / "_slikui.pyi"


def _load_stubgen():
    spec = importlib.util.spec_from_file_location("_nb_stubgen", STUBGEN)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod  # dataclasses resolve types via sys.modules
    spec.loader.exec_module(mod)
    return mod


def generate() -> str:
    """The stub text for the currently importable slikui._slikui."""
    import slikui._slikui as ext

    sg = _load_stubgen()
    gen = sg.StubGen(ext, include_docstrings=True,
                     patterns=sg.load_pattern_file(str(PATTERNS)))
    gen.put(ext)
    return gen.get()


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true",
                   help="exit 1 if the committed stub is out of date")
    args = p.parse_args(argv)
    text = generate()
    if args.check:
        if STUB.read_text(encoding="utf-8") != text:
            print(f"{STUB.relative_to(ROOT)} is stale: run tools/gen_stubs.py")
            return 1
        print("stub up to date")
        return 0
    STUB.write_text(text, encoding="utf-8")
    print(f"wrote {STUB.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
